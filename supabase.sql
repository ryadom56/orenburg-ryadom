create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 3 and 90),
  price numeric(12,2) not null check (price >= 0),
  category text not null,
  description text not null,
  contact text not null,
  photo_url text,
  created_at timestamptz not null default now()
);
alter table public.listings enable row level security;
drop policy if exists "Listings are public to read" on public.listings;
create policy "Listings are public to read" on public.listings for select using (true);
drop policy if exists "Users can create own listings" on public.listings;
create policy "Users can create own listings" on public.listings for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users can delete own listings" on public.listings;
create policy "Users can delete own listings" on public.listings for delete to authenticated using (auth.uid() = user_id);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('listing-photos', 'listing-photos', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg','image/png','image/webp'];
drop policy if exists "Listing photos are public to read" on storage.objects;
create policy "Listing photos are public to read" on storage.objects for select using (bucket_id = 'listing-photos');
drop policy if exists "Users upload photos to own folder" on storage.objects;
create policy "Users upload photos to own folder" on storage.objects for insert to authenticated with check (bucket_id = 'listing-photos' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Users delete photos from own folder" on storage.objects;
create policy "Users delete photos from own folder" on storage.objects for delete to authenticated using (bucket_id = 'listing-photos' and (storage.foldername(name))[1] = auth.uid()::text);
